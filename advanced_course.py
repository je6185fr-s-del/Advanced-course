def parse_med_index_from_filename(fname: str):
    """
    Robustly extract med index from filenames like:
    '..._med1.csv', '...med2...', '...MED3...'
    Prefer the last occurrence to avoid earlier 'med' strings in folders.
    """
    base = os.path.basename(str(fname))
    hits = re.findall(r'(?i)med\s*([0-9]+)', base)
    return int(hits[-1]) if hits else None

def process_trace(df, bl_window=BASELINE_WINDOW_POINTS, smooth_window=SMOOTH_WINDOW_POINTS):
    t = df["time_min"].values
    y = df["intensity"].values
    base     = rolling_min_baseline(y, window=bl_window)
    y_corr   = np.maximum(y - base, 0.0)
    y_smooth = smooth_ma(y_corr, window=smooth_window)
    return t, y_smooth

def make_overlay_zoom_peaks(data, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    plots_dir = os.path.join(out_dir, "plots")
    os.makedirs(plots_dir, exist_ok=True)

    if not data:
        raise RuntimeError("No chromatograms parsed (empty dataset).")

    # --- Select med1/med2/med3 specifically (not "first 3 alphabetically") ---
    picked = []
    for fname, df in data.items():
        med_idx = parse_med_index_from_filename(fname)
        if med_idx is not None:
            picked.append((med_idx, fname, df))

    if not picked:
        raise RuntimeError("Could not find any files with 'med<number>' in the filename.")

    picked.sort(key=lambda x: x[0])  # med1, med2, med3, ...

    # keep only first 3 unique med indices
    selected = []
    seen = set()
    for med_idx, fname, df in picked:
        if med_idx in seen:
            continue
        selected.append((med_idx, fname, df))
        seen.add(med_idx)
        if len(selected) >= MAX_TRACES:
            break

    if len(selected) < 2:
        raise RuntimeError(f"Only found {len(selected)} med-indexed chromatograms; expected 3 (med1/med2/med3).")

    colors = ["tab:blue", "tab:orange", "tab:green"]

    traces = []
    lefts, rights = [], []

    # --- Process and find peak bounds for each trace ---
    for i, (med_idx, fname, df) in enumerate(selected):
        t, y = process_trace(df)

        met = usp_tailing(t, y, frac=TAILING_FRACTION)
        if met is None:
            continue

        # peak bounds at the chosen fraction (5% by default)
        left_t  = met["left_time_min"]
        right_t = met["right_time_min"]

        # store for global x-lims
        lefts.append(left_t)
        rights.append(right_t)

        # optional normalization for overlay comparison
        y_plot = y.copy()
        if NORMALIZE_TO_MAX:
            m = float(np.max(y_plot))
            if m > 0:
                y_plot = y_plot / m

        traces.append({
            "med_idx": med_idx,
            "fname": fname,
            "t": t,
            "y": y_plot,
            "rt": met["apex_time_min"],
            "color": colors[i % len(colors)],
        })

    if not traces:
        raise RuntimeError("No usable peaks detected after processing.")

    # --- Auto-zoom limits from peak bounds across all traces ---
    x_min = float(min(lefts) - PEAK_MARGIN_MIN)
    x_max = float(max(rights) + PEAK_MARGIN_MIN)

    # y max within the zoom window
    y_zoom_max = 0.0
    for tr in traces:
        mask = (tr["t"] >= x_min) & (tr["t"] <= x_max)
        if np.any(mask):
            y_zoom_max = max(y_zoom_max, float(np.max(tr["y"][mask])))

    if y_zoom_max <= 0:
        y_zoom_max = max(float(np.max(tr["y"])) for tr in traces)

    # --- Plot ---
    fig, ax = plt.subplots(figsize=(9, 5))

    for tr in traces:
        label = f"Sample {tr['med_idx']} (RT {tr['rt']:.2f})"
        ax.plot(tr["t"], tr["y"], linewidth=2.2, color=tr["color"], label=label)

        # RT label directly above apex
        apex_idx = int(np.argmax(tr["y"]))
        apex_x = float(tr["t"][apex_idx])
        apex_y = float(tr["y"][apex_idx])

        # Only annotate if apex is inside the zoom window
        if x_min <= apex_x <= x_max:
            ax.annotate(
                f"{tr['rt']:.2f}",
                xy=(apex_x, apex_y),
                xytext=(0, 10),
                textcoords="offset points",
                ha="center", va="bottom",
                fontsize=10,
                color=tr["color"]
            )

    ax.set_title(f"{MEDRONIC_CONC_LABEL} - Overlay (peaks, zoomed)")
    ax.set_xlabel("Time (min)")
    ax.set_ylabel("Intensity (norm.)" if NORMALIZE_TO_MAX else "Intensity (a.u.)")

    ax.set_xlim(x_min, x_max)
    ax.set_ylim(0, y_zoom_max * 1.12)

