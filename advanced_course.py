def pretty_title(fname, inferred_pH=None, series=""):
    """Return a clean title string for the plot."""
    if fname in CUSTOM_TITLES:
        return CUSTOM_TITLES[fname]
    stem = os.path.splitext(fname)[0].replace("_", " ")
    if inferred_pH is not None and not (isinstance(inferred_pH, float) and np.isnan(inferred_pH)):
        stem += f" | pH {inferred_pH:g}"
    if series:
        stem += f" | {series}"
    return stem

