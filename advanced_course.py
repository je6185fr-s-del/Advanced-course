def peak_metrics(t, y):
    t = np.asarray(t, float)
    y = np.asarray(y, float)
    if t.size < 3 or np.nanmax(y) <= 0:
        return dict(max_intensity=np.nan, t_apex=np.nan, tailing_factor=np.nan)
    imax = int(np.nanargmax(y))
    y_max = float(y[imax]); t_apex = float(t[imax])
    level = 0.05 * y_max  # 5%

    # left crossing
    t_left = np.nan
    for i in range(imax-1, -1, -1):
        if y[i] <= level <= y[i+1]:
            x0, y0 = t[i], y[i]; x1, y1 = t[i+1], y[i+1]
            frac = 0 if y1==y0 else (level - y0)/(y1 - y0)
            t_left = float(x0 + frac*(x1 - x0)); break
    # right crossing
    t_right = np.nan
    for i in range(imax, len(y)-1):
        if y[i] >= level >= y[i+1]:
            x0, y0 = t[i], y[i]; x1, y1 = t[i+1], y[i+1]
            frac = 0 if y1==y0 else (level - y0)/(y1 - y0)
            t_right = float(x0 + frac*(x1 - x0)); break

    if not (np.isnan(t_left) or np.isnan(t_right)) and t_right > t_left and t_apex > t_left:
        w05 = t_right - t_left
        f = t_apex - t_left
        tail = w05 / (2.0 * f) if f > 0 else np.nan
    else:
        tail = np.nan
    return dict(max_intensity=y_max, t_apex=t_apex, tailing_factor=tail)

