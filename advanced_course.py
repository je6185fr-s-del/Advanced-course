def infer_ph_from_name(name: str):
    m = re.search(r'(?i)pH\s*([0-9]{1,2})(?:[._-]?([0-9]))?', name)
    if m:
        whole, frac = m.group(1), m.group(2)
        if frac is None:
            return float(whole)
        if len(whole) == 2:  # "45"->4.5, "88"->8.8
            return float(f"{whole[0]}.{frac}")
        return float(f"{whole}.{frac}")
    return None

def parse_compiled_chrom_file(path):
    raw = pd.read_csv(path)
    if "source_file" not in raw.columns or "CHROMATOGRAM" not in raw.columns:
        raise ValueError(f"{path}: missing required columns 'source_file' and/or 'CHROMATOGRAM'.")
    results = {}
    for fname, grp in raw.groupby("source_file", sort=False):
        lines = grp["CHROMATOGRAM"].astype(str).tolist()
        # find "Time(min),..." header line
        start_idx = 0
        for i in range(min(10, len(lines))):
            if "Time" in lines[i] and "," in lines[i]:
                start_idx = i + 1
                break
        t, y = [], []
        for line in lines[start_idx:]:
            if "," not in line:
                continue
            a, b = line.split(",", 1)
            try:
                t.append(float(a)); y.append(float(b))
            except ValueError:
                pass
        if len(t) < MIN_POINTS_REQUIRED:
            continue
        df = pd.DataFrame({"time_min": np.array(t), "intensity": np.array(y)})
        df["inferred_pH"] = grp["inferred_pH"].iloc[0] if "inferred_pH" in grp.columns else infer_ph_from_name(fname)
        df["series"] = grp["series"].iloc[0] if "series" in grp.columns else ""
        results[fname] = df
    return results

def rolling_min_baseline(y, window):
    s = pd.Series(y)
    base = s.rolling(max(3, window), min_periods=1, center=True).min()
    base = base.rolling(max(3, window//5), min_periods=1, center=True).mean()
    return base.values

def smooth_ma(y, window):
    if window <= 1:
        return y
    w = np.ones(window) / window
    return np.convolve(y, w, mode="same")

def usp_tailing(time, y_proc, frac=0.05):
    y = np.asarray(y_proc); t = np.asarray(time)
    if y.size < 3 or np.max(y) <= 0:
        return None
    idx_max = int(np.argmax(y))
    apex_t = float(t[idx_max]); apex_h = float(y[idx_max])
    level = float(frac * apex_h)

    # Left crossing
    i = idx_max
    while i > 0 and y[i] > level: i -= 1
    left_t = float(t[0]) if i == 0 else (
        float(t[i]) if t[i+1] == t[i] or y[i+1] == y[i]
        else float(t[i] + (level - y[i]) * (t[i+1] - t[i]) / (y[i+1] - y[i]))
    )

    # Right crossing
    i = idx_max
    n = len(y)
    while i < n-1 and y[i] > level: i += 1
    right_t = float(t[-1]) if i == n-1 else (
        float(t[i]) if y[i] == y[i-1]
        else float(t[i-1] + (level - y[i-1]) * (t[i] - t[i-1]) / (y[i] - y[i-1]))
    )

    W05   = right_t - left_t
    flead = apex_t - left_t
    tail  = float("nan") if flead <= 0 else W05 / (2.0 * flead)
    return {
        "apex_time_min": apex_t,
        "apex_height": apex_h,
        "level_fraction": float(frac),
        "level_value": level,
        "left_time_min": left_t,
        "right_time_min": right_t,
        "W_at_level_min": W05,
        "f_leading_min": flead,
        "USP_tailing": tail,
        "apex_index": int(idx_max),
    }

def process_and_plot(input_path, out_dir,
                     bl_window=BASELINE_WINDOW_POINTS,
                     smooth_window=SMOOTH_WINDOW_POINTS,
                     frac=TAILING_FRACTION):
    os.makedirs(out_dir, exist_ok=True)
    plots_dir = os.path.join(out_dir, "plots")
    os.makedirs(plots_dir, exist_ok=True)

    data = parse_compiled_chrom_file(input_path)
    if not data:
        raise RuntimeError(f"No chromatograms parsed from {input_path}.")

    summary_rows = []
    for fname, df in data.items():
        t = df["time_min"].values
        y = df["intensity"].values

        # Baseline correction + smoothing
        base     = rolling_min_baseline(y, window=bl_window)
        y_corr   = np.maximum(y - base, 0.0)
        y_smooth = smooth_ma(y_corr, window=smooth_window)

        # Metrics
        met = usp_tailing(t, y_smooth, frac=frac)
        if met is None:
            continue

        # ---------- PLOT (colored, clean, with NL + RT label; extra headroom) ----------
        fig, ax = plt.subplots(figsize=(8, 4.5))

        color = next(COLOR_CYCLE)
        ax.plot(t, y_smooth, linewidth=1.6, color=color)

        # Add headroom so the RT label doesn't collide
        ymax = float(np.max(y_smooth))
        apex_y = float(met["apex_height"])
        ax.set_ylim(top=max(ymax, apex_y) * 1.25)

        # Apex RT label above the peak
        ax.annotate(
            f"RT {met['apex_time_min']:.2f} min",
            xy=(met["apex_time_min"], met["apex_height"]),
            xytext=(0, 14),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=10,
        )

        # Top-right box with intensity as NL and USP TF
        ax.text(
            0.98, 0.98,
            f"NL: {met['apex_height']:.2E}\nUSP TF: {met['USP_tailing']:.2f}",
            transform=ax.transAxes,
            ha="right",
            va="top",
            fontsize=10,
            bbox=dict(boxstyle="round", fc="white", alpha=0.65, lw=0),
        )

        # Title using helper
        title_text = pretty_title(
            fname,
            df["inferred_pH"].iloc[0] if "inferred_pH" in df.columns else None,
            df["series"].iloc[0] if "series" in df.columns else ""
        )
        ax.set_title(title_text)
        ax.set_xlabel("Time (min)")
        ax.set_ylabel("Intensity (a.u.)")
        # Optional: avoid 1e6 scientific scaling on y-axis ticks
        # ax.ticklabel_format(style="plain", axis="y")
        fig.tight_layout()

        out_png = os.path.join(plots_dir, f"{os.path.splitext(fname)[0]}_chrom.png")
        fig.savefig(out_png, dpi=150)
        plt.close(fig)
        # -------------------------------------------------------------------

        # Summary row
        row = {
            "source_file": fname,
            "inferred_pH": df["inferred_pH"].iloc[0],
            "series": df["series"].iloc[0] if "series" in df.columns else "",
        }
        row.update(met)
        summary_rows.append(row)

    summary = pd.DataFrame(summary_rows)
    out_csv = os.path.join(out_dir, "summary.csv")
    summary.to_csv(out_csv, index=False)
    return out_csv, plots_dir

